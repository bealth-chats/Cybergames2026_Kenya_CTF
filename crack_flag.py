import sys

# The coupling table is 16 bytes: 0xc5 0x23 0xd9 0xa0 0xb5 0x67 0x1f 0x65 0xaf 0xfb 0x42 0x47 0x18 0x18 0x36 0x52
# Let's write out the LCG sequence.
# It initializes 16 nibbles? Wait, "The LFSR initialises 16 nibbles via a simple LCG (multiply by 0x6d, add 0x3d) XOR'd with a coupling table"
# LCG state starts at what? 0?
# x_0 = 0
# x_n = (x_{n-1} * 0x6d + 0x3d) & 0xff
state = 0
coupling_table = [0xc5, 0x23, 0xd9, 0xa0, 0xb5, 0x67, 0x1f, 0x65, 0xaf, 0xfb, 0x42, 0x47, 0x18, 0x18, 0x36, 0x52]

for i in range(16):
    state = (state * 0x6d + 0x3d) & 0xff
    print(chr(state ^ coupling_table[i]), end="")
print()

